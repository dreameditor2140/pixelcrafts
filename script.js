// Animate hero section on page load
function animateHeroOnLoad() {
    const heroElements = document.querySelectorAll('.hero-content .scroll-animate');
    heroElements.forEach((el, index) => {
        setTimeout(() => {
            el.classList.add('animate');
        }, index * 200);
    });
}

