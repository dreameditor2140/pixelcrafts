// Contact via WhatsApp
function contactViaWhatsApp(productId) {
    const product = products.find(p => p.id === productId);
    if (!product) return;

    const phoneNumber = '917359657806';
    const message = encodeURIComponent(
        `Hello Pixel Craft,\n\nI'm interested in: *${product.name}*\n\n` +
        `Description: ${product.description}\n` +
        (product.price ? `Price: ${product.price}\n` : '') +
        `\nPlease provide more information about this product.\n\nThank you!`
    );

    const whatsappUrl = `https://wa.me/${phoneNumber}?text=${message}`;
    window.open(whatsappUrl, '_blank');
}

// Setup event listeners
function setupEventListeners() {
    // Search functionality
    searchInput.addEventListener('input', handleSearch);

    // Filter buttons
    filterButtons.forEach(btn => {
        btn.addEventListener('click', () => handleFilter(btn));
    });

    // Mobile menu toggle
    mobileMenuToggle.addEventListener('click', toggleMobileMenu);

    // Close modal
    modalClose.addEventListener('click', closeModal);
    productModal.addEventListener('click', (e) => {
        if (e.target === productModal) {
            closeModal();
        }
    });

    // Close modal on Escape key
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && productModal.classList.contains('active')) {
            closeModal();
        }
    });

    // Update active nav link on scroll
    window.addEventListener('scroll', updateActiveNavLink);
}

// Handle search
function handleSearch() {
    const searchTerm = searchInput.value.toLowerCase().trim();
    applyFilters(searchTerm);
}

// Handle filter
function handleFilter(button) {
    // Update active state
    filterButtons.forEach(btn => btn.classList.remove('active'));
    button.classList.add('active');

    // Get category
    const category = button.dataset.category;
    const searchTerm = searchInput.value.toLowerCase().trim();

    applyFilters(searchTerm, category);
}

// Apply filters
function applyFilters(searchTerm = '', category = 'all') {
    filteredProducts = products.filter(product => {
        const matchesSearch = !searchTerm ||
            product.name.toLowerCase().includes(searchTerm) ||
            product.description.toLowerCase().includes(searchTerm) ||
            (product.details && product.details.toLowerCase().includes(searchTerm));

        const matchesCategory = category === 'all' || product.category === category;

        return matchesSearch && matchesCategory;
    });

    displayProducts(filteredProducts);
}

// Toggle mobile menu
function toggleMobileMenu() {
    navMenu.classList.toggle('active');
    mobileMenuToggle.classList.toggle('active');
}

// Close modal
function closeModal() {
    productModal.classList.remove('active');
    document.body.style.overflow = '';
}

// Setup smooth scrolling
function setupSmoothScrolling() {
    navLinks.forEach(link => {
        link.addEventListener('click', (e) => {
            const href = link.getAttribute('href');
            if (href.startsWith('#')) {
                e.preventDefault();
                const targetId = href.substring(1);
                const targetSection = document.getElementById(targetId);

                if (targetSection) {
                    const offsetTop = targetSection.offsetTop - 80;
                    window.scrollTo({
                        top: offsetTop,
                        behavior: 'smooth'
                    });

                    // Update active nav link
                    navLinks.forEach(nav => nav.classList.remove('active'));
                    link.classList.add('active');

                    // Close mobile menu if open
                    navMenu.classList.remove('active');
                }
            }
        });
    });
}

// Update active nav link on scroll
function updateActiveNavLink() {
    const sections = document.querySelectorAll('.section');
    const scrollPos = window.scrollY + 100;

    sections.forEach(section => {
        const sectionTop = section.offsetTop;
        const sectionHeight = section.offsetHeight;
        const sectionId = section.getAttribute('id');

        if (scrollPos >= sectionTop && scrollPos < sectionTop + sectionHeight) {
            navLinks.forEach(link => {
                link.classList.remove('active');
                if (link.getAttribute('href') === `#${sectionId}`) {
                    link.classList.add('active');
                }
            });
        }
    });
}

// Setup scroll animations
function setupScrollAnimations() {
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('animate');
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    // Observe all scroll-animate elements
    const animateElements = document.querySelectorAll('.scroll-animate, .scroll-fade, .scroll-scale, .scroll-slide-left, .scroll-slide-right, .shadow-on-scroll');
    animateElements.forEach(el => observer.observe(el));

    // Observe product cards with staggered delay
    const productCards = document.querySelectorAll('.product-card');
    productCards.forEach((card, index) => {
        card.classList.add('scroll-animate');
        if (index % 4 === 1) card.classList.add('scroll-animate-delay-1');
        if (index % 4 === 2) card.classList.add('scroll-animate-delay-2');
        if (index % 4 === 3) card.classList.add('scroll-animate-delay-3');
        observer.observe(card);
    });

    // Observe section headers
    const sectionHeaders = document.querySelectorAll('.section-header');
    sectionHeaders.forEach(header => {
        header.classList.add('scroll-fade');
        observer.observe(header);
    });

    // Observe feature items
    const featureItems = document.querySelectorAll('.feature-item');
    featureItems.forEach((item, index) => {
        item.classList.add('scroll-slide-left');
        if (index % 3 === 1) item.classList.add('scroll-animate-delay-1');
        if (index % 3 === 2) item.classList.add('scroll-animate-delay-2');
        observer.observe(item);
    });

    // Observe contact info
    const contactInfo = document.querySelector('.contact-info');
    if (contactInfo) {
        contactInfo.classList.add('scroll-slide-left');
        observer.observe(contactInfo);
    }
}

// Setup navbar scroll shadow
function setupNavbarScroll() {
    const navbar = document.querySelector('.navbar');
    let lastScroll = 0;

    window.addEventListener('scroll', () => {
        const currentScroll = window.pageYOffset;

        if (currentScroll > 50) {
            navbar.classList.add('scrolled');
        } else {
            navbar.classList.remove('scrolled');
        }

        lastScroll = currentScroll;
    });
}

